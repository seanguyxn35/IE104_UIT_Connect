/* =====================================================================
   UIT CONNECT – LƯỢC ĐỒ CSDL cho PostgreSQL / Supabase
   Sinh tự động từ database/schema.sql (bản SQL Server) – sửa bản gốc rồi chuyển lại,
   hoặc từ nay coi file này là bản chính.
   Khác bản SQL Server:
     - Tên bảng/cột dạng snake_case (LabApplication.TopicID -> lab_application.topic_id)
     - IDENTITY -> GENERATED BY DEFAULT AS IDENTITY, NVARCHAR -> VARCHAR, NVARCHAR(MAX) -> TEXT,
       DATETIME2 -> TIMESTAMPTZ, BIT -> BOOLEAN, TINYINT -> SMALLINT, SYSDATETIME() -> now()
     - So sánh chuỗi phân biệt hoa/thường (SQL Server dùng collation CI)
   ===================================================================== */

/* =====================================================================
