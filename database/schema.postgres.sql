-- 1. [PDF] Account (+ EmailVerifiedAt, TermsAcceptedAt, AvatarURL, LastLoginAt, CreatedAt)
CREATE TABLE account (
    account_id        INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_account PRIMARY KEY,
    email            VARCHAR(150) NOT NULL CONSTRAINT uq_account_email UNIQUE,
    password_hash     VARCHAR(255) NULL,      -- NULL: SV/GV chỉ đăng nhập qua UIT SSO
    role             VARCHAR(20)  NOT NULL,
    is_active         BOOLEAN NOT NULL DEFAULT true,
    email_verified_at  TIMESTAMPTZ(0) NULL,      -- (+) đăng ký bước 3: nhập mã 6 chữ số
    terms_accepted_at  TIMESTAMPTZ(0) NULL,      -- (+) cam kết Quy chế SHTT & Liêm chính học thuật
    avatar_url        VARCHAR(255) NULL,      -- (+) "Đổi ảnh"
    last_login_at      TIMESTAMPTZ(0) NULL,
    created_at        TIMESTAMPTZ(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_account_role CHECK (role IN ('Student','Lecturer','Business','Admin')),
    -- Màn đăng ký: SV bắt buộc email @gm.uit.edu.vn, GV dùng email @uit.edu.vn
    CONSTRAINT ck_account_email_domain CHECK (
        (role <> 'Student'  OR email LIKE '%@gm.uit.edu.vn') AND
        (role <> 'Lecturer' OR email LIKE '%@uit.edu.vn')),
    -- Doanh nghiệp / Admin đăng nhập bằng email & mật khẩu nên bắt buộc có mật khẩu
    CONSTRAINT ck_account_password CHECK (password_hash IS NOT NULL OR role IN ('Student','Lecturer'))
);

-- [MỚI] Liên kết đăng nhập UIT SSO / Microsoft 365 (màn 02: "MSSV / Mã GV hoặc email @gm.uit.edu.vn")
CREATE TABLE external_login (
    provider     VARCHAR(20)  NOT NULL,
    provider_key  VARCHAR(150) NOT NULL,    -- định danh phía SSO (UPN / MSSV / mã GV)
    account_id    INT NOT NULL CONSTRAINT fk_external_login_account REFERENCES account(account_id) ON DELETE CASCADE,
    linked_at     TIMESTAMPTZ(0) NOT NULL DEFAULT now(),
    CONSTRAINT pk_external_login PRIMARY KEY (provider, provider_key),
    CONSTRAINT uq_external_login_account UNIQUE (account_id, provider),
    CONSTRAINT ck_external_login_provider CHECK (provider IN ('UIT_SSO','Microsoft365'))
);

-- [MỚI] Mã xác thực: kích hoạt email (mã 6 số, hạn 10 phút, gửi lại sau 60 giây)
--        và quên mật khẩu (mã 6 số hoặc link, hạn 15 phút)
CREATE TABLE verification_code (
    code_id        INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_verification_code PRIMARY KEY,
    account_id     INT NOT NULL CONSTRAINT fk_verification_code_account REFERENCES account(account_id) ON DELETE CASCADE,
    purpose       VARCHAR(20)  NOT NULL,
    code_hash      VARCHAR(255) NOT NULL,   -- lưu bản băm của mã / token, không lưu mã gốc
    expires_at     TIMESTAMPTZ(0) NOT NULL,
    attempt_count  SMALLINT NOT NULL DEFAULT 0,
    consumed_at    TIMESTAMPTZ(0) NULL,
    created_at     TIMESTAMPTZ(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_verification_code_purpose CHECK (purpose IN ('Email_Verify','Password_Reset')),
    CONSTRAINT ck_verification_code_expiry CHECK (expires_at > created_at)
);
CREATE INDEX ix_verification_code_account ON verification_code (account_id, purpose, created_at DESC);

-- [MỚI] Phiên đăng nhập: "Ghi nhớ đăng nhập trên thiết bị này (30 ngày)", đăng xuất
CREATE TABLE login_session (
    session_id     BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_login_session PRIMARY KEY,
    account_id     INT NOT NULL CONSTRAINT fk_login_session_account REFERENCES account(account_id) ON DELETE CASCADE,
    token_hash     VARCHAR(255) NOT NULL CONSTRAINT uq_login_session_token UNIQUE,
    is_remembered  BOOLEAN NOT NULL DEFAULT false,
    device_info    VARCHAR(255) NULL,
    created_at     TIMESTAMPTZ(0) NOT NULL DEFAULT now(),
    expires_at     TIMESTAMPTZ(0) NOT NULL,
    revoked_at     TIMESTAMPTZ(0) NULL
);

-- 2. [PDF] StudentProfile (+ lớp, khóa, GPA, ĐRL, liên kết, chế độ hiển thị – màn "Hồ sơ năng lực & CV")
CREATE TABLE student_profile (
    student_id            INT NOT NULL CONSTRAINT pk_student_profile PRIMARY KEY
                         CONSTRAINT fk_student_profile_account REFERENCES account(account_id) ON DELETE CASCADE,
    full_name             VARCHAR(150) NOT NULL,
    student_code          VARCHAR(20)   NOT NULL CONSTRAINT uq_student_profile_code UNIQUE,   -- MSSV
    major_id              INT NOT NULL CONSTRAINT fk_student_profile_major REFERENCES major(major_id),  -- khoa suy ra từ Major
    class_name            VARCHAR(30)   NULL,    -- (+) 'KHMT2021'
    cohort               VARCHAR(10)   NULL,    -- (+) 'K18'
    enrollment_year       SMALLINT      NULL,    -- (+) 2021
    graduation_year       SMALLINT      NULL,    -- (+) dự kiến tốt nghiệp
    gpa                  DECIMAL(4,2)  NULL,    -- (+) thang 10 (lọc học bổng, xếp ứng viên)
    training_score        SMALLINT       NULL,    -- (+) điểm rèn luyện
    headline             VARCHAR(255) NULL,    -- (+) 'Sinh viên KHMT & Nghiên cứu AI'
    github_url            VARCHAR(255)  NULL,
    linkedin_url          VARCHAR(255)  NULL,
    is_open_to_opportunity  BOOLEAN NOT NULL DEFAULT true,   -- (+) "Sẵn sàng nhận Lab / Đề tài DN"
    profile_visibility    VARCHAR(20) NOT NULL DEFAULT 'Public',
    generated_cv_url      VARCHAR(255)  NULL,    -- [PDF] link CV hệ thống tạo tự động
    updated_at            TIMESTAMPTZ(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_student_profile_gpa CHECK (gpa BETWEEN 0 AND 10),
    CONSTRAINT ck_student_profile_drl CHECK (training_score BETWEEN 0 AND 100),
    CONSTRAINT ck_student_profile_visibility CHECK (profile_visibility IN ('Public','Partners_Only','Private'))
);

-- 3. [PDF] LecturerProfile (LabName → LabID; + mã GV, học hàm/học vị, chỉ số khoa học, suất hướng dẫn)
CREATE TABLE lecturer_profile (
    lecturer_id           INT NOT NULL CONSTRAINT pk_lecturer_profile PRIMARY KEY
                         CONSTRAINT fk_lecturer_profile_account REFERENCES account(account_id) ON DELETE CASCADE,
    full_name             VARCHAR(150) NOT NULL,
    lecturer_code         VARCHAR(20)   NOT NULL CONSTRAINT uq_lecturer_profile_code UNIQUE,  -- 'GV01024'
    academic_title        VARCHAR(10)   NULL,    -- (+) 'ThS', 'TS', 'PGS.TS', 'GS.TS'
    faculty_id            INT NOT NULL CONSTRAINT fk_lecturer_profile_faculty REFERENCES faculty(faculty_id),
    lab_id                INT NULL CONSTRAINT fk_lecturer_profile_lab REFERENCES lab(lab_id),   -- [PDF] LabName
    position_title        VARCHAR(150) NULL,    -- (+) 'Trưởng Lab CV&PR'
    research_area         TEXT NULL,    -- [PDF] giới thiệu hướng nghiên cứu
