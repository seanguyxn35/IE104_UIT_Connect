-- Khoa: ô chọn "Khoa" khi đăng ký, bộ lọc "Khoa / Lab" ở trang chủ, danh bạ GV
CREATE TABLE faculty (
    faculty_id  INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_faculty PRIMARY KEY,
    code       VARCHAR(20)   NOT NULL CONSTRAINT uq_faculty_code UNIQUE,   -- 'KHMT', 'KTMT'...
    name       VARCHAR(150) NOT NULL CONSTRAINT uq_faculty_name UNIQUE
);

-- Chuyên ngành đào tạo (ô chọn "Chuyên ngành đào tạo" khi đăng ký)
CREATE TABLE major (
    major_id    INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_major PRIMARY KEY,
    faculty_id  INT NOT NULL CONSTRAINT fk_major_faculty REFERENCES faculty(faculty_id),
    name       VARCHAR(150) NOT NULL,
    CONSTRAINT uq_major_faculty_name UNIQUE (faculty_id, name)
);

-- Lĩnh vực nghiên cứu: dropdown "Lĩnh vực" ở trang chủ, bộ lọc kho tài liệu, bài toán DN, học bổng
CREATE TABLE field (
    field_id    INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_field PRIMARY KEY,
    name       VARCHAR(100) NOT NULL CONSTRAINT uq_field_name UNIQUE
);

-- Công nghệ & kỹ năng: thẻ PyTorch, TensorRT... trên CV, nhóm, tài nguyên, tin tuyển, bài toán DN
CREATE TABLE skill (
    skill_id    INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_skill PRIMARY KEY,
    name       VARCHAR(100) NOT NULL CONSTRAINT uq_skill_name UNIQUE,
    category   VARCHAR(50)  NULL     -- 'Lĩnh vực & Mô hình AI', 'Ngôn ngữ & Frameworks', 'Hạ tầng & Công cụ'
);

-- Phòng thí nghiệm: thay cột LabName (chữ tự do) trong LecturerProfile của PDF,
-- để lọc theo "Khoa / Lab" và gắn Lab cho GV, nhóm, đề tài
CREATE TABLE lab (
    lab_id           INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_lab PRIMARY KEY,
    faculty_id       INT NOT NULL CONSTRAINT fk_lab_faculty REFERENCES faculty(faculty_id),
    name            VARCHAR(150) NOT NULL CONSTRAINT uq_lab_name UNIQUE,
    focus_area       VARCHAR(255) NULL,   -- 'Thị giác máy tính & Nhận dạng'
    room            VARCHAR(50)  NULL,   -- 'E4.12'
    head_lecturer_id  INT NULL,             -- trưởng Lab; FK thêm sau khi tạo LecturerProfile
    is_verified      BOOLEAN NOT NULL DEFAULT false   -- nhãn "Lab Xác thực"
);

