    orcid                VARCHAR(30)   NULL,
    h_index               SMALLINT      NULL,    -- (+) danh bạ GV sắp xếp "H-index cao nhất"
    citation_count        INT           NULL,
    is_accepting_advisees  BOOLEAN NOT NULL DEFAULT true,   -- công tắc "Đang nhận hướng dẫn"
    max_advisees          SMALLINT NOT NULL DEFAULT 5, -- "Còn 2/5 suất"
    verified_at           TIMESTAMPTZ(0)  NULL,    -- hồ sơ được Phòng TCCB & KHCN chứng thực
    updated_at            TIMESTAMPTZ(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_lecturer_profile_title CHECK (academic_title IN ('CN','ThS','TS','PGS.TS','GS.TS'))
);
ALTER TABLE lab ADD CONSTRAINT fk_lab_head_lecturer
