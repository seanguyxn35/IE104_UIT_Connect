-- Suất hướng dẫn của GV: "Còn 2/5 suất" (danh bạ GV), "Suất hướng dẫn: 3/5 đã nhận" (GV 05)
CREATE VIEW vw_lecturer_advising_slot WITH (security_invoker = true) AS
SELECT  l.lecturer_id,
        l.full_name,
        l.is_accepting_advisees,
        l.max_advisees,
        COUNT(p.project_id) AS active_projects,
        CASE WHEN l.max_advisees > COUNT(p.project_id)
             THEN l.max_advisees - COUNT(p.project_id) ELSE 0 END AS remaining_slots
FROM lecturer_profile AS l
LEFT JOIN research_project AS p
       ON p.supervisor_id = l.lecturer_id
      AND p.is_principal_investigator = false
      AND p.progress_status NOT IN ('Completed','Cancelled')
GROUP BY l.lecturer_id, l.full_name, l.is_accepting_advisees, l.max_advisees;

-- "Việc cần xử lý" trên trang chủ GV: yêu cầu hướng dẫn, đề tài chờ thẩm định, đơn xin vào Lab
CREATE VIEW vw_lecturer_pending_task WITH (security_invoker = true) AS
SELECT  l.lecturer_id,
        (SELECT COUNT(*) FROM advisor_request AS r
          WHERE r.lecturer_id = l.lecturer_id AND r.status = 'Pending') AS pending_advisor_requests,
        (SELECT COUNT(*) FROM review_assignment AS a
          WHERE a.lecturer_id = l.lecturer_id AND a.status IN ('Pending','In_Review')) AS pending_reviews,
        (SELECT COUNT(*) FROM lab_application AS ap
           JOIN lab_topic AS t ON t.topic_id = ap.topic_id
          WHERE t.lecturer_id = l.lecturer_id AND ap.status = 'Pending') AS pending_lab_applications
FROM lecturer_profile AS l;

