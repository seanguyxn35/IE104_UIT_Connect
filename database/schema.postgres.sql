CREATE VIEW vw_resource_catalog WITH (security_invoker = true) AS
SELECT  r.resource_id, r.resource_code, r.type, r.title, r.abstract, r.trl_level,
        r.review_score, r.interest_count, r.view_count, r.published_at,
        f.name  AS field_name,
        fa.name AS faculty_name,
        lb.name AS lab_name,
        t.team_name,
        l.academic_title AS lecturer_title,
        l.full_name      AS lecturer_name
FROM academic_resource AS r
LEFT JOIN field           AS f  ON f.field_id     = r.field_id
LEFT JOIN faculty         AS fa ON fa.faculty_id  = r.faculty_id
LEFT JOIN lab             AS lb ON lb.lab_id      = r.lab_id
LEFT JOIN student_team     AS t  ON t.team_id      = r.owner_team_id
LEFT JOIN lecturer_profile AS l  ON l.lecturer_id  = r.lecturer_id
WHERE r.status = 'Published';

