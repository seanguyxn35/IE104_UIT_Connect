/* Hộp thư kết nối của Doanh nghiệp (DN-08): proposal SV / GV / Lab gửi tới bài toán R&D.
   Chạy trên Supabase → SQL Editor. Chạy lại nhiều lần vẫn an toàn (IF NOT EXISTS, xóa rồi tạo lại CHECK).
   Chỉ THÊM cột / bảng và NỚI ràng buộc CHECK nên không làm hỏng dữ liệu hiện có.

   1. business_problem
      - problem_code: mã hiển thị 'RD-2026-084' (giao diện, liên kết giữa các trang dùng mã này)
      - status thêm 'Draft' (bản nháp, DN-05)
   2. connection_request
      - student_id: proposal của SV cá nhân (nhóm chốt 26/11/2026: không coi là nhóm 1 người)
      - initiated_by thêm 'Student'; status thêm 'Scheduled' (tab "Đã hẹn trao đổi")
      - title, cover_letter (thư giới thiệu), tags, trl_label, fit_score (mức phù hợp 0–100),
        decline_reason, read_at (NULL = proposal mới, chưa xem)
   3. connection_meeting: lịch hẹn trao đổi của một proposal (lịch mới nhất là lịch hiện hành)
   4. rd_attachment: tệp đính kèm (bài toán / proposal / phòng đàm phán), tệp nằm ở bucket riêng tư "rd-files"
*/

BEGIN;

-- 1. business_problem ---------------------------------------------------
ALTER TABLE business_problem
    ADD COLUMN IF NOT EXISTS problem_code VARCHAR(30) NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_business_problem_code
    ON business_problem (problem_code) WHERE problem_code IS NOT NULL;

ALTER TABLE business_problem DROP CONSTRAINT IF EXISTS ck_business_problem_status;
ALTER TABLE business_problem ADD CONSTRAINT ck_business_problem_status
    CHECK (status IN ('Draft','Pending_Approval','Open','In_Progress','Closed','Rejected'));

-- 2. connection_request -------------------------------------------------
ALTER TABLE connection_request
    ADD COLUMN IF NOT EXISTS student_id     INT          NULL,
    ADD COLUMN IF NOT EXISTS title          VARCHAR(255) NULL,
    ADD COLUMN IF NOT EXISTS cover_letter   TEXT         NULL,
    ADD COLUMN IF NOT EXISTS tags           VARCHAR(60)[] NOT NULL DEFAULT '{}',
    ADD COLUMN IF NOT EXISTS trl_label      VARCHAR(60)  NULL,
    ADD COLUMN IF NOT EXISTS fit_score      SMALLINT     NULL,
    ADD COLUMN IF NOT EXISTS decline_reason TEXT         NULL,
    ADD COLUMN IF NOT EXISTS read_at        TIMESTAMPTZ(0) NULL;

ALTER TABLE connection_request DROP CONSTRAINT IF EXISTS fk_connection_request_student;
ALTER TABLE connection_request ADD CONSTRAINT fk_connection_request_student
    FOREIGN KEY (student_id) REFERENCES student_profile(student_id);

ALTER TABLE connection_request DROP CONSTRAINT IF EXISTS ck_connection_request_party;
ALTER TABLE connection_request ADD CONSTRAINT ck_connection_request_party
    CHECK (team_id IS NOT NULL OR lecturer_id IS NOT NULL OR student_id IS NOT NULL);

ALTER TABLE connection_request DROP CONSTRAINT IF EXISTS ck_connection_request_initiator;
ALTER TABLE connection_request ADD CONSTRAINT ck_connection_request_initiator
    CHECK (initiated_by IN ('Business','Team','Lecturer','Student'));

ALTER TABLE connection_request DROP CONSTRAINT IF EXISTS ck_connection_request_status;
ALTER TABLE connection_request ADD CONSTRAINT ck_connection_request_status
    CHECK (status IN ('Submitted','Scheduled','In_Discussion','Contracted','Completed','Declined','Cancelled'));

ALTER TABLE connection_request DROP CONSTRAINT IF EXISTS ck_connection_request_fit;
ALTER TABLE connection_request ADD CONSTRAINT ck_connection_request_fit
    CHECK (fit_score IS NULL OR fit_score BETWEEN 0 AND 100);

CREATE INDEX IF NOT EXISTS ix_connection_request_business
    ON connection_request (business_id, status, created_at DESC);

-- 3. connection_meeting -------------------------------------------------
CREATE TABLE IF NOT EXISTS connection_meeting (
    meeting_id             INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_connection_meeting PRIMARY KEY,
    request_id             INT NOT NULL CONSTRAINT fk_connection_meeting_request
                               REFERENCES connection_request(request_id) ON DELETE CASCADE,
    start_at               TIMESTAMPTZ(0) NOT NULL,
    mode                   VARCHAR(100) NOT NULL,     -- 'Trực tuyến (Google Meet)', 'Tại UIT'...
    agenda                 VARCHAR(255) NULL,
    created_by_account_id  INT NOT NULL CONSTRAINT fk_connection_meeting_creator REFERENCES account(account_id),
    created_at             TIMESTAMPTZ(0) NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_connection_meeting_request ON connection_meeting (request_id, start_at DESC);

-- 4. rd_attachment ------------------------------------------------------
CREATE TABLE IF NOT EXISTS rd_attachment (
    attachment_id          INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_rd_attachment PRIMARY KEY,
    owner_type             VARCHAR(20) NOT NULL,      -- bảng sở hữu tệp
    owner_id               INT NOT NULL,              -- khóa chính của dòng sở hữu
    file_name              VARCHAR(255) NOT NULL,
    storage_path           VARCHAR(500) NOT NULL CONSTRAINT uq_rd_attachment_path UNIQUE,  -- đường dẫn trong bucket "rd-files"
    size_bytes             INT NOT NULL,
    doc_type               VARCHAR(100) NULL,         -- 'Proposal kỹ thuật', 'Hồ sơ năng lực'...
    uploaded_by_account_id INT NULL CONSTRAINT fk_rd_attachment_uploader REFERENCES account(account_id),
    created_at             TIMESTAMPTZ(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_rd_attachment_owner CHECK (owner_type IN ('Problem','Request','Negotiation')),
    CONSTRAINT ck_rd_attachment_size  CHECK (size_bytes > 0)
);
CREATE INDEX IF NOT EXISTS ix_rd_attachment_owner ON rd_attachment (owner_type, owner_id);

-- RLS bật trên mọi bảng (frontend không gọi Supabase trực tiếp; backend dùng secret key)
ALTER TABLE connection_meeting ENABLE ROW LEVEL SECURITY;
ALTER TABLE rd_attachment      ENABLE ROW LEVEL SECURITY;

COMMIT;
