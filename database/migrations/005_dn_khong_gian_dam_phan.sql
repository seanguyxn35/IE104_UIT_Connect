/* Không gian đàm phán của Doanh nghiệp (DN-09 danh sách phòng, DN-16 trong phòng).
   Chạy SAU 004_dn_hop_thu_ket_noi.sql, trên Supabase → SQL Editor. Chạy lại nhiều lần vẫn an toàn.

   Một "phòng đàm phán" = một connection_request đã được DN chấp nhận (In_Discussion / Contracted / Completed).
   1. connection_request
      - room_opened_at: lúc DN chấp nhận proposal, mở phòng
      - business_last_read_at: lần cuối DN đọc mục Trao đổi (đếm tin chưa đọc)
      - proposed_budget: ngân sách đối tác đề xuất (nếu có)
      - contract_code, contracted_at: mã và ngày ký thỏa thuận (ký NGOÀI hệ thống, chỉ ghi nhận)
   2. connection_step: 3 bước Technical (Trao đổi kỹ thuật) → NDA_IP → Contract (Hợp đồng).
      Bước xong khi CẢ HAI bên xác nhận; bước sau chỉ mở khi bước trước xong (máy chủ kiểm tra).
      Bước Contract đủ hai bên → connection_request chuyển 'Contracted' (CHECK sẵn có vẫn bảo đảm
      Contracted chỉ khi student_confirmed và business_confirmed đều true).
   3. connection_message: trao đổi theo lượt trong phòng (KHÔNG phải chat realtime – ngoài phạm vi dự án)
*/

BEGIN;

-- 1. connection_request -------------------------------------------------
ALTER TABLE connection_request
    ADD COLUMN IF NOT EXISTS room_opened_at        TIMESTAMPTZ(0) NULL,
    ADD COLUMN IF NOT EXISTS business_last_read_at TIMESTAMPTZ(0) NULL,
    ADD COLUMN IF NOT EXISTS proposed_budget       DECIMAL(18,2)  NULL,
    ADD COLUMN IF NOT EXISTS contract_code         VARCHAR(30)    NULL,
    ADD COLUMN IF NOT EXISTS contracted_at         TIMESTAMPTZ(0) NULL;

ALTER TABLE connection_request DROP CONSTRAINT IF EXISTS ck_connection_request_budget;
ALTER TABLE connection_request ADD CONSTRAINT ck_connection_request_budget
    CHECK (proposed_budget IS NULL OR proposed_budget >= 0);
CREATE UNIQUE INDEX IF NOT EXISTS ux_connection_request_contract_code
    ON connection_request (contract_code) WHERE contract_code IS NOT NULL;

-- 2. connection_step ----------------------------------------------------
CREATE TABLE IF NOT EXISTS connection_step (
    request_id             INT NOT NULL CONSTRAINT fk_connection_step_request
                               REFERENCES connection_request(request_id) ON DELETE CASCADE,
    step_code              VARCHAR(20) NOT NULL,
    business_confirmed     BOOLEAN NOT NULL DEFAULT false,
    partner_confirmed      BOOLEAN NOT NULL DEFAULT false,
    business_confirmed_at  TIMESTAMPTZ(0) NULL,
    partner_confirmed_at   TIMESTAMPTZ(0) NULL,
    note                   VARCHAR(150) NULL,      -- 'Đang soạn thảo', 'Đã ký MoA 01/09/2026'...
    CONSTRAINT pk_connection_step PRIMARY KEY (request_id, step_code),
    CONSTRAINT ck_connection_step_code CHECK (step_code IN ('Technical','NDA_IP','Contract')),
    CONSTRAINT ck_connection_step_business_at CHECK (business_confirmed = (business_confirmed_at IS NOT NULL)),
    CONSTRAINT ck_connection_step_partner_at  CHECK (partner_confirmed  = (partner_confirmed_at  IS NOT NULL))
);

-- 3. connection_message -------------------------------------------------
CREATE TABLE IF NOT EXISTS connection_message (
    message_id         INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_connection_message PRIMARY KEY,
    request_id         INT NOT NULL CONSTRAINT fk_connection_message_request
                           REFERENCES connection_request(request_id) ON DELETE CASCADE,
    sender_type        VARCHAR(10) NOT NULL,     -- Business | Partner | System (thông báo của hệ thống)
    sender_account_id  INT NULL CONSTRAINT fk_connection_message_sender REFERENCES account(account_id),
    content            TEXT NOT NULL,
    created_at         TIMESTAMPTZ(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_connection_message_sender  CHECK (sender_type IN ('Business','Partner','System')),
    CONSTRAINT ck_connection_message_account CHECK (sender_type = 'System' OR sender_account_id IS NOT NULL),
    CONSTRAINT ck_connection_message_length  CHECK (char_length(content) BETWEEN 1 AND 1000)
);
CREATE INDEX IF NOT EXISTS ix_connection_message_request ON connection_message (request_id, created_at);

ALTER TABLE connection_step    ENABLE ROW LEVEL SECURITY;
ALTER TABLE connection_message ENABLE ROW LEVEL SECURITY;

COMMIT;
