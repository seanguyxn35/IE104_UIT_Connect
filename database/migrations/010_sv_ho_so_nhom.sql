/* SV-06 tab "Thông tin nhóm": trưởng nhóm cập nhật hồ sơ nhóm.
   - team_field: tối đa 3 "Lĩnh vực trọng tâm" mỗi nhóm. Cột student_team.field_id vẫn là lĩnh vực CHÍNH
     (lĩnh vực chọn đầu tiên) để các chức năng đang đọc cột này không đổi. Nhóm chưa có dòng nào trong team_field
     thì hiểu là chỉ có field_id (không chép dữ liệu cũ sang).
   - cap_nhat_ho_so_nhom: sửa student_team, team_field, team_skill (và thêm kỹ năng mới vào danh mục skill)
     trong MỘT transaction. Giới hạn số lượng và độ dài do máy chủ kiểm tra. Chỉ backend (service_role) được gọi.
   Chỉ thêm bảng và hàm; không sửa hay xóa dữ liệu. Chạy lại nhiều lần vẫn an toàn. */

BEGIN;

-- Khóa chính RIÊNG, không ghép (team_id, field_id): nếu ghép, PostgREST coi đây là bảng nối nhiều-nhiều và mọi
-- truy vấn dạng student_team(..., field(name)) đang có sẽ lỗi PGRST201 vì có hai đường tới bảng field.
CREATE TABLE IF NOT EXISTS team_field (
    team_field_id  INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_team_field PRIMARY KEY,
    team_id        INT NOT NULL CONSTRAINT fk_team_field_team REFERENCES student_team(team_id) ON DELETE CASCADE,
    field_id       INT NOT NULL CONSTRAINT fk_team_field_field REFERENCES field(field_id),
    CONSTRAINT uq_team_field UNIQUE (team_id, field_id)
);
ALTER TABLE team_field ENABLE ROW LEVEL SECURITY;

-- p_changes chỉ chứa khóa cần đổi: name, description, facultyId, fieldIds (mảng), skills (mảng tên).
-- Trả { "error": mã } hoặc {}.
CREATE OR REPLACE FUNCTION cap_nhat_ho_so_nhom(p_team_id INT, p_actor_id INT, p_changes JSONB)
RETURNS JSONB
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
    v_status   student_team.status%TYPE;
    v_role     team_member.role_in_team%TYPE;
    v_fields   INT[];
    v_name     TEXT;
    v_skill_id INT;
BEGIN
    SELECT status INTO v_status FROM student_team WHERE team_id = p_team_id FOR UPDATE;
    IF NOT FOUND THEN RETURN jsonb_build_object('error', 'TEAM_NOT_FOUND'); END IF;

    SELECT role_in_team INTO v_role FROM team_member WHERE team_id = p_team_id AND student_id = p_actor_id;
    IF NOT FOUND THEN RETURN jsonb_build_object('error', 'TEAM_NOT_FOUND'); END IF;
    IF v_role <> 'Leader' THEN RETURN jsonb_build_object('error', 'NOT_TEAM_LEADER'); END IF;
    IF v_status <> 'Active' THEN RETURN jsonb_build_object('error', 'TEAM_INACTIVE'); END IF;

    -- Kiểm tra hết mã tham chiếu trước khi ghi bất cứ thứ gì
    IF p_changes ->> 'facultyId' IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM faculty WHERE faculty_id = (p_changes ->> 'facultyId')::INT) THEN
        RETURN jsonb_build_object('error', 'FACULTY_NOT_FOUND');
    END IF;
    IF p_changes ? 'fieldIds' THEN
        v_fields := ARRAY(SELECT value::INT FROM jsonb_array_elements_text(p_changes -> 'fieldIds') WITH ORDINALITY ORDER BY ordinality);
        IF (SELECT count(*) FROM field WHERE field_id = ANY (v_fields)) <> cardinality(v_fields) THEN
            RETURN jsonb_build_object('error', 'FIELD_NOT_FOUND');
        END IF;
    END IF;

    IF p_changes ? 'name' THEN
        UPDATE student_team SET team_name = p_changes ->> 'name' WHERE team_id = p_team_id;
    END IF;
    IF p_changes ? 'description' THEN
        UPDATE student_team SET description = p_changes ->> 'description' WHERE team_id = p_team_id;
    END IF;
    IF p_changes ? 'facultyId' THEN
        UPDATE student_team SET faculty_id = (p_changes ->> 'facultyId')::INT WHERE team_id = p_team_id;
    END IF;

    IF p_changes ? 'fieldIds' THEN
        DELETE FROM team_field WHERE team_id = p_team_id;
        INSERT INTO team_field (team_id, field_id) SELECT p_team_id, unnest(v_fields);
        UPDATE student_team SET field_id = v_fields[1] WHERE team_id = p_team_id;  -- mảng rỗng -> NULL
    END IF;

    IF p_changes ? 'skills' THEN
        DELETE FROM team_skill WHERE team_id = p_team_id;
        FOR v_name IN SELECT value FROM jsonb_array_elements_text(p_changes -> 'skills') LOOP
            -- Cùng quy tắc với kỹ năng SV: so tên không phân biệt hoa thường, chưa có thì thêm vào danh mục
            SELECT skill_id INTO v_skill_id FROM skill WHERE lower(name) = lower(v_name) ORDER BY skill_id LIMIT 1;
            IF NOT FOUND THEN
                INSERT INTO skill (name) VALUES (v_name) ON CONFLICT (name) DO NOTHING RETURNING skill_id INTO v_skill_id;
                IF v_skill_id IS NULL THEN  -- giao dịch khác vừa thêm cùng tên
                    SELECT skill_id INTO v_skill_id FROM skill WHERE name = v_name;
                END IF;
            END IF;
            INSERT INTO team_skill (team_id, skill_id) VALUES (p_team_id, v_skill_id) ON CONFLICT DO NOTHING;
        END LOOP;
    END IF;

    RETURN '{}'::jsonb;
END;
$$;

REVOKE ALL ON FUNCTION cap_nhat_ho_so_nhom(INT, INT, JSONB) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION cap_nhat_ho_so_nhom(INT, INT, JSONB) TO service_role;

COMMIT;
